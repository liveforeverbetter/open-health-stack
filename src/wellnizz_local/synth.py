"""Generate a fully synthetic person: lab results (CSV and FHIR), daily wearable data and a VCF.

Every value comes from a seeded pseudo-random generator. Nothing is derived from
any real person. The same seed always gives byte-identical files. Generated
files are released under CC0-1.0 and carry a SYNTHETIC marker.
"""

from __future__ import annotations

import datetime as _dt
import json
import random
from pathlib import Path

HEADER = "SYNTHETIC DATA generated by wellnizz-local synth (seed={seed}). Not from any real person. CC0-1.0."

# Illustrative reference ranges that travel with the synthetic results. Real
# ranges always come from the reporting laboratory.
LAB_PANEL = [
    # name, LOINC, unit, ref_low, ref_high, synthetic draw (low, high), decimals
    ("Ferritin", "2276-4", "ng/mL", 30.0, 400.0, (12.0, 260.0), 0),
    ("Hemoglobin", "718-7", "g/dL", 13.5, 17.5, (12.5, 17.0), 1),
    ("Glucose", "2345-7", "mg/dL", 70.0, 99.0, (75.0, 112.0), 0),
    ("Hemoglobin A1c", "4548-4", "%", 4.0, 5.6, (4.8, 6.1), 1),
    ("LDL cholesterol (calculated)", "13457-7", "mg/dL", None, 100.0, (70.0, 165.0), 0),
    ("25-hydroxyvitamin D", "1989-3", "ng/mL", 30.0, 100.0, (14.0, 48.0), 0),
    ("TSH", "3016-3", "mIU/L", 0.4, 4.0, (0.8, 3.6), 2),
]

REFERENCE_SITES = [  # chrom, pos, ref, alt, rsid (match the bundled reference set)
    ("1", 11796321, "G", "A", "rs1801133"),
    ("6", 26092913, "G", "A", "rs1800562"),
    ("6", 26090951, "C", "G", "rs1799945"),
    ("19", 44908684, "T", "C", "rs429358"),
    ("19", 44908822, "C", "T", "rs7412"),
    ("2", 135851076, "G", "A", "rs4988235"),
    ("15", 74749576, "C", "A", "rs762551"),
    ("11", 66560624, "C", "T", "rs1815739"),
]


def _labs(rng: random.Random, when: str) -> list[dict]:
    out = []
    for name, loinc, unit, lo, hi, (a, b), dec in LAB_PANEL:
        v = round(rng.uniform(a, b), dec)
        out.append({"collected_date": when, "loinc": loinc, "name": name, "value": v, "unit": unit,
                    "ref_low": lo, "ref_high": hi})
    return out


def _fmt(x) -> str:
    if x is None:
        return ""
    return str(int(x)) if float(x).is_integer() else str(x)


def write_lab_csv(path: Path, rows: list[dict], seed: int) -> None:
    lines = [f"# {HEADER.format(seed=seed)}", "collected_date,loinc,name,value,unit,ref_low,ref_high"]
    for r in rows:
        lines.append(",".join([r["collected_date"], r["loinc"], f'"{r["name"]}"', _fmt(r["value"]), r["unit"],
                               _fmt(r["ref_low"]), _fmt(r["ref_high"])]))
    path.write_text("\n".join(lines) + "\n", "utf-8")


def write_fhir(path: Path, rows: list[dict], seed: int) -> None:
    entries = []
    for i, r in enumerate(rows, start=1):
        rr = {}
        if r["ref_low"] is not None:
            rr["low"] = {"value": r["ref_low"], "unit": r["unit"]}
        if r["ref_high"] is not None:
            rr["high"] = {"value": r["ref_high"], "unit": r["unit"]}
        obs = {
            "resourceType": "Observation", "id": f"synthetic-{i}", "status": "final",
            "code": {"coding": [{"system": "http://loinc.org", "code": r["loinc"], "display": r["name"]}], "text": r["name"]},
            "subject": {"display": "Synthetic Person 001"},
            "effectiveDateTime": r["collected_date"],
            "valueQuantity": {"value": r["value"], "unit": r["unit"]},
        }
        if rr:
            obs["referenceRange"] = [rr]
        entries.append({"fullUrl": f"urn:uuid:synthetic-{seed}-{i}", "resource": obs})
    bundle = {"resourceType": "Bundle", "type": "collection",
              "meta": {"tag": [{"code": "synthetic", "display": HEADER.format(seed=seed)}]}, "entry": entries}
    path.write_text(json.dumps(bundle, indent=1) + "\n", "utf-8")


def write_wearables(path: Path, rng: random.Random, seed: int, end: _dt.date, days: int = 90) -> None:
    lines = [f"# {HEADER.format(seed=seed)}", "date,steps,sleep_minutes,hrv_rmssd_ms,resting_hr_bpm"]
    hrv_base = rng.uniform(38, 62)
    rhr_base = rng.uniform(52, 66)
    for k in range(days):
        day = end - _dt.timedelta(days=days - 1 - k)
        if rng.random() < 0.04:
            continue  # a missing day, as in real exports
        late_dip = max(0, k - (days - 10)) * rng.uniform(0.6, 1.2)  # small HRV dip in the last 10 days
        steps = max(500, int(rng.gauss(8200, 2600)))
        sleep = max(240, int(rng.gauss(425, 45)))
        hrv = round(max(12.0, rng.gauss(hrv_base, 5.0) - late_dip), 1)
        rhr = round(rng.gauss(rhr_base, 2.5) + late_dip * 0.3, 1)
        lines.append(f"{day.isoformat()},{steps},{sleep},{hrv},{rhr}")
    path.write_text("\n".join(lines) + "\n", "utf-8")


def write_vcf(path: Path, rng: random.Random, seed: int, decoys: int = 40) -> None:
    head = [
        "##fileformat=VCFv4.2",
        f"##comment={HEADER.format(seed=seed)}",
        "##reference=GRCh38",
        '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">',
    ] + [f"##contig=<ID={c}>" for c in [str(i) for i in range(1, 23)]]
    head.append("#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tSYNTHETIC_001")
    records = []
    for chrom, pos, ref, alt, rsid in REFERENCE_SITES:
        gt = rng.choice(["0/0", "0/1", "0/1", "1/1"])
        if gt == "0/0":
            continue  # variant-only VCF: reference calls are not listed
        records.append((int(chrom), pos, rsid, ref, alt, gt))
    bases = "ACGT"
    for _ in range(decoys):
        ref = rng.choice(bases)
        alt = rng.choice([b for b in bases if b != ref])
        records.append((rng.randint(1, 22), rng.randint(1_000_000, 90_000_000), ".", ref, alt, rng.choice(["0/1", "1/1"])))
    records.sort()
    body = [f"{c}\t{p}\t{i}\t{r}\t{a}\t50\tPASS\t.\tGT\t{g}" for c, p, i, r, a, g in records]
    path.write_text("\n".join(head + body) + "\n", "utf-8")


def generate(out_dir: Path | str, seed: int = 7) -> dict[str, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    rng = random.Random(seed)
    files = {
        "labs_csv": out / "labs_2026-03-02.csv",
        "labs_fhir": out / "labs_2026-09-14.fhir.json",
        "wearables": out / "wearable_daily.csv",
        "vcf": out / "synthetic_001.vcf",
    }
    write_lab_csv(files["labs_csv"], _labs(rng, "2026-03-02"), seed)
    write_fhir(files["labs_fhir"], _labs(rng, "2026-09-14"), seed)
    write_wearables(files["wearables"], rng, seed, end=_dt.date(2026, 11, 15))
    write_vcf(files["vcf"], rng, seed)
    return files
